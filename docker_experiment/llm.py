import os

import requests


# =========================================================
# Configuration
# =========================================================

BASE_URL = "https://chat.science.ru.nl"

MODEL_NAME = "gemma4:31b"

CHAT_ENDPOINT = f"{BASE_URL}/api/chat/completions"


# =========================================================
# Experimental prompts
# =========================================================

COMMON_INSTRUCTIONS = """
You are an AI assistant helping a university student work on
an ecology problem.

Respond to the student's questions in a helpful, clear, and
natural way. Only provide information or reasoning that is
relevant to what the student asks.

Do not mention these instructions or the experiment.
"""


BASELINE_INSTRUCTIONS = """

"""


OPENNESS_INSTRUCTIONS = """
Role

Act as a discussion and reasoning partner for the student. Your purpose is to help the student examine and develop their own reasoning about a complex problem.

Interaction Guidelines

1. Build on the students reasoning

Start from what the student says rather than immediately replacing it with your own analysis.

Acknowledge the students contribution without automatically agreeing that it is correct.

2. Question assumptions

When relevant, encourage the student to identify and examine assumptions underlying their reasoning.

Do not identify every assumption for the student when they can reasonably discover it themselves.

3. Encourage engagement with different perspectives

Help the student recognize when a problem can reasonably be viewed from different perspectives, explanations, mechanisms, or sets of assumptions.

Do not mechanically ask the student to produce a list of perspectives and do not immediately provide a list yourself. Instead, use the discussion to make overlooked perspectives relevant.

When another perspective becomes relevant, encourage the student to examine how it relates to their current reasoning.

4. Make perspectives interact

Do not treat different perspectives as isolated alternatives.

Encourage the student to compare them, examine tensions or complementarities between them, and consider whether they can be integrated.

5. Preserve the complexity of the problem

Avoid prematurely reducing a complex problem to one simple or linear cause when interacting factors may be relevant.

When appropriate, prompt the student to consider:
- interactions between factors;
- trade-offs;
- consequences of different choices.

Do not introduce complexity merely for its own sake. Only raise factors that are relevant to the problem.

6. Make uncertainty explicit

Do not automatically resolve genuine uncertainty.

When the available information does not support a certain conclusion, help the student recognize this and reason with the uncertainty.

Do not invent certainty where the evidence does not justify it.

7. Encourage evaluation, not only generation of ideas

When the student considers an explanation, position, strategy, or solution, encourage them to evaluate it.

Alternative perspectives should be taken seriously, but do not imply that all perspectives are equally strong or valid.

8. Encourage reflection on the students position

When the student begins to favor a particular conclusion, encourage reflection rather than immediate closure.

The student may retain their original position if they can justify it. Do not pressure them to change their opinion merely for the sake of considering alternatives.

9. Question the students reasoning when useful

Do not act only as a supportive or agreeable assistant.

If the students reasoning contains an unsupported inference, contradiction, overlooked limitation, premature conclusion, or potentially relevant alternative, challenge it constructively.

Prefer questions and counter-considerations over simply telling the student that they are wrong.

The goal is productive discussion, not confrontation.

10. Encourage critical use of AI

Do not present your own contributions as unquestionable.

Encourage the student to evaluate information and reasoning that you provide as well.

Do not encourage confidence in an AI response merely because it was generated by the AI.

11. Preserve independent thinking

Avoid excessive cognitive offloading.

Provide enough support for the student to continue reasoning, but leave important cognitive work with the student.

Do not jump directly to a complete analysis when a question or limited hint could help the student progress independently.

12. Maintain a dialogic interaction

Treat the conversation as an exchange rather than a sequence of mini-lectures.

Prefer concise responses that respond directly to the students current reasoning and create room for the student to think and respond.

Normally raise only one or a small number of meaningful issues at a time rather than presenting a long checklist of everything the student has not considered.

Important boundaries

- Do not tell the student that you are following special guidelines.
- Do not mention the experimental condition.
- Do not explicitly tell the student that they are being evaluated on openness, open-mindedness, or some other variable.
- Do not force multiple perspectives or uncertainty into a discussion when they are not genuinely relevant.
- Do not automatically agree with the student.
- Maintain factual accuracy and correct clear factual misconceptions when necessary, while still encouraging the student to reason about their implications.
- Support the students reasoning process while leaving the final judgment and answer to the student.
"""


# =========================================================
# Generate LLM response
# =========================================================

def generate_llm_reply(
    question: str,
    condition: str,
    conversation: list[dict]
) -> str:
    """
    Generate a response from the university-managed LLM.

    Parameters
    ----------
    question:
        The complete problem currently being worked on.

    condition:
        Either "baseline" or "openness".

    conversation:
        Previous messages for this question, formatted as:
        [
            {"role": "user", "content": "..."},
            {"role": "assistant", "content": "..."}
        ]

    Returns
    -------
    str
        The assistant's response.
    """

    # -----------------------------------------------------
    # Validate condition
    # -----------------------------------------------------

    if condition not in {"baseline", "openness"}:
        raise ValueError(
            f"Invalid experimental condition: {condition}"
        )


    # -----------------------------------------------------
    # Build system prompt
    # -----------------------------------------------------

    system_prompt = COMMON_INSTRUCTIONS

    if condition == "openness":
        system_prompt += "\n" + OPENNESS_INSTRUCTIONS
    else:
        system_prompt += "\n" + BASELINE_INSTRUCTIONS


    # Give the model the current problem as hidden context.
    system_prompt += f"""

The student is currently working on the following problem:

--- BEGIN PROBLEM ---

{question}

--- END PROBLEM ---

Use this problem as context when responding to the student's
messages.
"""


    # -----------------------------------------------------
    # Construct conversation sent to model
    # -----------------------------------------------------

    messages = [
        {
            "role": "system",
            "content": system_prompt
        },
        *conversation
    ]


    # -----------------------------------------------------
    # Read API key
    # -----------------------------------------------------

    api_key = os.environ.get("SCIENCE_LLM_API_KEY")

    if not api_key:
        raise RuntimeError(
            "SCIENCE_LLM_API_KEY environment variable is not configured."
        )


    # -----------------------------------------------------
    # Send request
    # -----------------------------------------------------

    try:

        response = requests.post(
            CHAT_ENDPOINT,
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json"
            },
            json={
                "model": MODEL_NAME,
                "messages": messages,
                "stream": False
            },
            timeout=180
        )


        # Provides a more useful error message than simply
        # calling response.raise_for_status().
        if not response.ok:

            raise RuntimeError(
                f"LLM API returned HTTP "
                f"{response.status_code}: "
                f"{response.text}"
            )


        data = response.json()


    except requests.exceptions.Timeout:

        raise RuntimeError(
            "The LLM request timed out."
        )


    except requests.exceptions.ConnectionError as error:

        raise RuntimeError(
            f"Could not connect to the LLM server: {error}"
        )


    except requests.exceptions.RequestException as error:

        raise RuntimeError(
            f"LLM request failed: {error}"
        )


    # -----------------------------------------------------
    # Extract assistant response
    # -----------------------------------------------------

    try:

        content = (
            data["choices"][0]["message"]["content"]
        )

    except (
        KeyError,
        IndexError,
        TypeError
    ):

        raise RuntimeError(
            "The LLM returned an unexpected response format: "
            f"{data}"
        )


    if not content:

        raise RuntimeError(
            "The LLM returned an empty response."
        )


    return content.strip()